"""Generate docs/source_profile.md from the source file (schema profile + identity).

Usage:  python scripts/profile_source.py [path/to/world_air_quality.csv]
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from pipeline.config import load_config  # noqa: E402
from pipeline.manifest import compare_to_manifest, inspect_source, load_manifest  # noqa: E402


def main() -> None:
    cfg = load_config()
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else cfg.path("source_file")
    manifest = load_manifest(cfg)
    ident = compare_to_manifest(inspect_source(src), manifest)
    raw = pd.read_csv(src, sep=";", dtype=str, keep_default_na=False, encoding="utf-8-sig")
    implicit = pd.read_csv(src, sep=";", encoding="utf-8-sig")  # pandas default NA semantics (= notebook)

    lines = [
        "# Source Profile — `world_air_quality.csv`",
        "",
        "_Generated by `scripts/profile_source.py`; do not edit by hand._",
        "",
        "## Identity",
        "",
        "| Property | Observed | Manifest | Match |",
        "|---|---|---|---|",
    ]
    for key in ("sha256", "size_bytes", "data_rows"):
        obs, exp = ident["observed"][key], manifest["file"][key]
        lines.append(f"| {key} | `{obs}` | `{exp}` | {'yes' if obs == exp else '**NO**'} |")
    lines += [
        f"| encoding | UTF-8{' with BOM' if ident['observed']['has_bom'] else ''} | {manifest['file']['encoding']} | |",
        f"| delimiter | `;` | `{manifest['file']['delimiter']}` | |",
        "",
        "## Column profile",
        "",
        "`empty` = literally empty field. `implicit NA` = additional non-empty strings that pandas'",
        "default `read_csv` silently converts to NaN (the original notebook relied on this).",
        "",
        "| Column | Inferred type | Distinct | Empty | Implicit NA (strings) | Example |",
        "|---|---|---|---|---|---|",
    ]
    for col in raw.columns:
        s = raw[col]
        empty = int((s == "").sum())
        implicit_mask = implicit[col].isna() & (s != "")
        implicit_vals = s[implicit_mask].value_counts().to_dict()
        imp = ", ".join(f"`{k}`×{v}" for k, v in implicit_vals.items()) or "0"
        kind = "float" if col == "Value" else ("timestamp (ISO-8601 +offset)" if col == "Last Updated" else "string")
        example = next((v for v in s if v), "")
        lines.append(f"| {col} | {kind} | {s.nunique()} | {empty} | {imp} | `{example[:40]}` |")

    vals = pd.to_numeric(raw["Value"])
    ts = pd.to_datetime(raw["Last Updated"], utc=True, format="ISO8601")
    lines += [
        "",
        "## Distributions",
        "",
        f"- **Rows:** {len(raw):,}; exact duplicate rows: {int(raw.duplicated().sum())}",
        f"- **Countries:** {raw['Country Code'].nunique()} codes; **locations:** {raw['Location'].nunique():,}; **sources:** {raw['Source Name'].nunique()}",
        f"- **Last Updated:** {ts.min().isoformat()} → {ts.max().isoformat()} (UTC); by year: "
        + ", ".join(f"{y}: {n:,}" for y, n in ts.dt.year.value_counts().sort_index().items()),
        f"- **Value:** min {vals.min()}, median {vals.median()}, max {vals.max()}; negative readings: {int((vals < 0).sum())}",
        "",
        "### Pollutant × unit",
        "",
        "| Pollutant | Unit | Rows |",
        "|---|---|---|",
    ]
    for (p, u), n in raw.groupby(["Pollutant", "Unit"]).size().sort_values(ascending=False).items():
        lines.append(f"| {p} | {u} | {n:,} |")
    lines += [
        "",
        "## Observations relevant to the pipeline",
        "",
        "- There is **no natural load/update timestamp**: `Last Updated` is the measurement time of the",
        "  latest reading per station/pollutant, not a record-change timestamp. Incremental ingestion is",
        "  therefore simulated with a source-row high-water mark (see README §Ingestion).",
        "- The same (Location, Pollutant, Last Updated) appears more than once (mostly the same reading",
        "  reported in both ppm and µg/m³), so staging de-duplicates on that key before the unit filter, as in",
        "  the notebook.",
        "- `TEMPERATURE` (117 rows) and `RELATIVEHUMIDITY` (66 rows) are too sparse for modelling — the",
        "  reason the original project switched to co-pollutant predictors.",
        "- The file is a static snapshot; source identity (checksum) replaces a recency check.",
        "",
        "## Licence / privacy",
        "",
        f"- Licence: {manifest['license_and_privacy']['license'].strip()}",
        f"- Personal data: {manifest['license_and_privacy']['personal_data'].strip()}",
        "",
    ]
    out = ROOT / "docs" / "source_profile.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
